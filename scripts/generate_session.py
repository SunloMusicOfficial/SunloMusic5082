import asyncio
import sys
import os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import sys
from ftmgram import Client
from config.settings import settings

# ANSI color codes for premium terminal look
RESET = "\033[0m"
RED = "\033[91m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
BLUE = "\033[94m"
CYAN = "\033[96m"
BOLD = "\033[1m"

BANNER = f"""{CYAN}{BOLD}
    ╔══════════════════════════════════════════════╗
    ║       🎵 SUNLO MUSIC - PREMIUM SESSION       ║
    ║             GENERATOR v1.0                   ║
    ╚══════════════════════════════════════════════╝
{RESET}"""

async def main():
    print(BANNER)
    print(f"{YELLOW}⚠️  IMPORTANT: Use the Assistant account (Not the Bot).{RESET}")
    print(f"{YELLOW}⚠️  Make sure your API_ID and API_HASH are set in .env{RESET}\n")

    if not settings.API_ID or not settings.API_HASH:
        print(f"{RED}❌ Error: API_ID or API_HASH is missing in your .env file!{RESET}")
        return

    try:
        print(f"{BLUE}🔄 Initializing secure connection...{RESET}")
        
        # in_memory=True so it doesn't create .session files locally
        async with Client(
            name=":memory:",
            api_id=settings.API_ID,
            api_hash=settings.API_HASH,
            in_memory=True
        ) as app:
            print(f"{BLUE}🔐 Logging in... Please check Telegram for OTP.{RESET}")
            
            # The login process happens here automatically
            me = await app.get_me()
            
            print(f"{GREEN}✅ Logged in as: {me.first_name} (@{me.username}){RESET}")
            print(f"{BLUE}⚙️  Generating Session String...{RESET}")
            
            session_string = await app.export_session_string()
            
            # Format the message for Saved Messages
            saved_msg = (
                "🎵 **Sunlo Music - Assistant Session** 🎵\n\n"
                "⚠️ **WARNING:** This string gives full access to your account. "
                "Do NOT share it with anyone.\n\n"
                "**Copy the string below and paste it in your `.env` file:**\n\n"
                f"`{session_string}`\n\n"
                "🚀 *Generated by Sunlo Music Premium Generator*"
            )

            print(f"{BLUE}📩 Sending session string to your Saved Messages...{RESET}")
            await app.send_message("me", saved_msg)
            
            print(f"\n{GREEN}{BOLD}✅ SUCCESS! Session generated successfully.{RESET}")
            print(f"{GREEN}Check your Telegram 'Saved Messages' to get the session string.{RESET}")
            print(f"{YELLOW}Add it to your .env file under SESSION_STRING={RESET}")
            
    except Exception as e:
        print(f"\n{RED}❌ Error occurred: {e}{RESET}")
        print(f"{YELLOW}Check your internet, API details, or OTP.{RESET}")

if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        print(f"\n{RED}Cancelled by user.{RESET}")
        sys.exit(0)
